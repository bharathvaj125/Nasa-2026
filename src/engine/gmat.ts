// Exports the player's orbit as a starter script for NASA's General Mission Analysis Tool (GMAT), so the
// game design can be taken into the same high-fidelity tool real NASA analysts use. The script is built
// from the documented GMAT script language; open it in GMAT and adjust epoch, force model and fidelity.
import { getScenario } from '../data/scenarios';
import { BODIES } from './physics';
import type { Design, Evaluation } from './types';

export function gmatSupported(design: Design): boolean {
  return getScenario(design.scenarioId).destination !== 'l2';
}

export function buildGmatScript(design: Design, ev: Evaluation): string {
  const scn = getScenario(design.scenarioId);
  const dest = scn.destination;
  const body = BODIES[dest];
  const gmatBody = dest === 'earth' ? 'Earth' : dest === 'moon' ? 'Luna' : 'Mars';
  const cs = dest === 'earth' ? 'EarthMJ2000Eq' : `${gmatBody}Inertial`;
  const sma = ev.orbit.aKm;
  const ecc = 0.0005;
  const raan = 0;
  const bodyArea = Math.max(1, ev.mass.mevDryKg / 150);
  const lines: string[] = [];
  const push = (s = '') => lines.push(s);

  push('%General Mission Analysis Tool (GMAT) script');
  push(`%Generated by CATALYX Mission Design Lab for the design "${design.name}"`);
  push(`%Scenario: ${scn.title} | destination: ${body.name} | design hash ${ev.designHash}`);
  push('%This is a starter script. Open in GMAT, review the force model and adjust before use.');
  push('');
  if (dest !== 'earth') {
    push(`Create CoordinateSystem ${cs};`);
    push(`GMAT ${cs}.Origin = ${gmatBody};`);
    push(`GMAT ${cs}.Axes = BodyInertial;`);
    push('');
  }
  push('%---------- Spacecraft');
  push('Create Spacecraft Sat;');
  push('GMAT Sat.DateFormat = UTCGregorian;');
  push("GMAT Sat.Epoch = '01 Jan 2030 12:00:00.000';");
  push(`GMAT Sat.CoordinateSystem = ${cs};`);
  push('GMAT Sat.DisplayStateType = Keplerian;');
  push(`GMAT Sat.SMA = ${sma.toFixed(3)};`);
  push(`GMAT Sat.ECC = ${ecc};`);
  push(`GMAT Sat.INC = ${ev.orbit.incDeg.toFixed(3)};`);
  push(`GMAT Sat.RAAN = ${raan};`);
  push('GMAT Sat.AOP = 0;');
  push('GMAT Sat.TA = 0;');
  push(`GMAT Sat.DryMass = ${ev.mass.mevDryKg.toFixed(1)};`);
  push('GMAT Sat.Cd = 2.2;');
  push('GMAT Sat.Cr = 1.8;');
  push(`GMAT Sat.DragArea = ${bodyArea.toFixed(2)};`);
  push(`GMAT Sat.SRPArea = ${bodyArea.toFixed(2)};`);
  push('');
  push('%---------- Force model');
  push('Create ForceModel Prop_ForceModel;');
  push(`GMAT Prop_ForceModel.CentralBody = ${gmatBody};`);
  push(`GMAT Prop_ForceModel.PrimaryBodies = {${gmatBody}};`);
  push(`GMAT Prop_ForceModel.PointMasses = {${dest === 'earth' ? 'Luna, Sun' : 'Earth, Sun'}};`);
  if (dest === 'earth') {
    push('GMAT Prop_ForceModel.Drag = MSISE90;');
    push('GMAT Prop_ForceModel.SRP = On;');
    push('GMAT Prop_ForceModel.GravityField.Earth.Degree = 8;');
    push('GMAT Prop_ForceModel.GravityField.Earth.Order = 8;');
    push("GMAT Prop_ForceModel.GravityField.Earth.PotentialFile = 'JGM2.cof';");
    push(`GMAT Prop_ForceModel.Drag.F107 = ${Math.round(110 * ev.solarActivity + 20)};`);
    push(`GMAT Prop_ForceModel.Drag.F107A = ${Math.round(110 * ev.solarActivity + 20)};`);
    push('GMAT Prop_ForceModel.Drag.MagneticIndex = 3;');
  } else {
    push('GMAT Prop_ForceModel.Drag = None;');
    push('GMAT Prop_ForceModel.SRP = On;');
    if (dest === 'moon') {
      push('GMAT Prop_ForceModel.GravityField.Luna.Degree = 20;');
      push('GMAT Prop_ForceModel.GravityField.Luna.Order = 20;');
      push("GMAT Prop_ForceModel.GravityField.Luna.PotentialFile = 'LP165P.cof';");
    } else {
      push('GMAT Prop_ForceModel.GravityField.Mars.Degree = 20;');
      push('GMAT Prop_ForceModel.GravityField.Mars.Order = 20;');
      push("GMAT Prop_ForceModel.GravityField.Mars.PotentialFile = 'Mars50c.cof';");
    }
  }
  push('');
  push('%---------- Propagator');
  push('Create Propagator Prop;');
  push('GMAT Prop.FM = Prop_ForceModel;');
  push('GMAT Prop.Type = RungeKutta89;');
  push('GMAT Prop.InitialStepSize = 60;');
  push('GMAT Prop.Accuracy = 9.999999999999999e-12;');
  push('GMAT Prop.MinStep = 0.001;');
  push('GMAT Prop.MaxStep = 2700;');
  push('GMAT Prop.MaxStepAttempts = 50;');
  push('');
  push('%---------- Output');
  push('Create ReportFile Report;');
  push("GMAT Report.Filename = 'catalyx_orbit_report.txt';");
  push('GMAT Report.Precision = 16;');
  push('GMAT Report.WriteHeaders = On;');
  push('GMAT Report.LeftJustify = On;');
  push('GMAT Report.ZeroFill = Off;');
  push('GMAT Report.FixedWidth = On;');
  push('GMAT Report.Delimiter = \' \';');
  push('GMAT Report.WriteReport = true;');
  push('');
  push('BeginMissionSequence;');
  push('');
  const days = Math.min(365, Math.max(30, Math.round(design.lifeMonths * 30.4)));
  push(`%Propagate for the planned mission life (capped at one year here)`);
  push(`For I = 1:${days};`);
  push('   Propagate Prop(Sat) {Sat.ElapsedDays = 1};');
  push(`   Report Report Sat.ElapsedDays Sat.${cs}.SMA Sat.${cs}.ECC Sat.${cs}.INC Sat.${gmatBody}.Altitude;`);
  push('EndFor;');
  return lines.join('\n') + '\n';
}
