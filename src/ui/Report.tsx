import { useState } from 'react';
import { ROLES, ROLE_ORDER } from '../data/roles';
import { getScenario } from '../data/scenarios';
import { fmt } from '../engine/evaluate';
import { buildGmatScript, gmatSupported } from '../engine/gmat';
import { marginItems } from '../engine/simulate';
import { shareUrl, useGame, type Result } from '../state/store';
import { Donut, HBar, Histogram, ScoreRing } from './charts';
import { Panel, Pill } from './kit';

function download(name: string, text: string, type = 'text/plain') {
  const url = URL.createObjectURL(new Blob([text], { type }));
  const a = document.createElement('a');
  a.href = url; a.download = name; a.click();
  setTimeout(() => URL.revokeObjectURL(url), 500);
}

function markdown(r: Result): string {
  const scn = getScenario(r.design.scenarioId);
  const { ev, mc, score } = r;
  const L: string[] = [];
  L.push(`# Mission report: ${r.design.name}`, '', `Scenario: **${scn.title}** (${scn.tagline})`, `Score: **${score.total.toFixed(0)}/100 (${score.grade})**: ${score.label}`, '');
  L.push('## Outcome', `- Full success in ${(mc.pFull * 100).toFixed(0)}% of 300 simulated flights, partial ${(mc.pPartial * 100).toFixed(0)}%, failure ${(mc.pFail * 100).toFixed(0)}%`, `- Expected science return: ${(mc.meanScienceFrac * 100).toFixed(0)}% of the scenario potential`, `- This flight: ${r.run.outcome} (${(r.run.scienceFrac * 100).toFixed(0)}% science)`, '');
  L.push('## Design', `- Launch: ${r.design.launcherId}; launch mass ${fmt(ev.mass.wetKg)} kg of ${fmt(ev.mass.capacityKg)} kg capacity`, `- Orbit: ${ev.orbit.body === 'l2' ? 'Sun-Earth L2 halo' : `${fmt(ev.orbit.altKm)} km, inclination ${ev.orbit.incDeg.toFixed(1)} deg, period ${fmt(ev.orbit.periodMin)} min`}`, `- Power: ${fmt(ev.power.eolW)} W end of life vs ${fmt(ev.power.avgLoadW)} W average load`, `- Data: ${fmt(ev.data.generatedGBday)} GB/day generated, ${fmt(ev.data.downlinkGBday)} GB/day downlinked`, `- Cost: $${fmt(ev.cost.totalM)}M of $${fmt(ev.cost.budgetM)}M`, `- Instruments: ${r.design.instrumentIds.join(', ')}`, '');
  L.push('## Why', ...r.insights.map((i) => `- **${i.title}** ${i.detail}${i.fix ? ' Fix: ' + i.fix : ''}`), '');
  L.push('---', 'Generated by CATALYX Mission Design Lab (NASA Space Apps Challenge 2026).');
  return L.join('\n');
}

export function Report() {
  const result = useGame((s) => s.result);
  const back = useGame((s) => s.backToLab);
  const refly = useGame((s) => s.refly);
  const team = useGame((s) => s.team);
  const best = useGame((s) => s.best);
  const [copied, setCopied] = useState(false);
  if (!result) return null;
  const { ev, mc, score, run, design, insights, priorities } = result;
  const scn = getScenario(design.scenarioId);
  const margins = marginItems(ev);
  const costParts = [
    { label: 'Hardware', value: ev.cost.hardwareM, color: '#5ee7ff' },
    { label: 'Integration & PM', value: ev.cost.integrationM + ev.cost.programM, color: '#b79cff' },
    { label: 'Reserve', value: ev.cost.reserveM, color: '#ffb454' },
    { label: 'Launch', value: ev.cost.launchM, color: '#7be495' },
    { label: 'Operations', value: ev.cost.opsM, color: '#ff8a9a' },
  ];
  const verification = [
    { req: 'Spacecraft fits the launch vehicle with ≥10% margin', ok: ev.mass.marginPct >= 10, val: `${ev.mass.marginPct.toFixed(0)}%` },
    { req: 'Power margin positive at end of life (≥10% preferred)', ok: ev.power.marginPct >= 10, val: `${ev.power.marginPct.toFixed(0)}%` },
    { req: 'At least 85% of science data returned to Earth', ok: ev.data.returnFrac >= 0.85, val: `${(ev.data.returnFrac * 100).toFixed(0)}%` },
    { req: 'Total cost within the cap', ok: ev.cost.totalM <= ev.cost.budgetM, val: `$${fmt(ev.cost.totalM)}M / $${fmt(ev.cost.budgetM)}M` },
    { req: 'Development fits the launch window', ok: ev.schedule.slipMonths === 0, val: `${fmt(ev.schedule.devMonths)} / ${ev.schedule.windowMonths} mo` },
    { req: 'Planned operating life achieved', ok: ev.nominalMonths + 0.5 >= design.lifeMonths, val: `${fmt(ev.nominalMonths)} / ${design.lifeMonths} mo` },
    { req: 'Primary objective ≥ 80% (full success)', ok: (run.objectiveAchievement[(scn.objectives.find((o) => o.primary) ?? scn.objectives[0]).id] ?? 0) >= 0.8, val: `${((run.objectiveAchievement[(scn.objectives.find((o) => o.primary) ?? scn.objectives[0]).id] ?? 0) * 100).toFixed(0)}% this flight` },
  ];
  const outcomeColor = run.outcome === 'full' ? 'var(--green)' : run.outcome === 'partial' ? 'var(--amber)' : 'var(--red)';
  return (
    <div className="container">
      <div className="panel" style={{ borderColor: outcomeColor }}>
        <div className="row" style={{ gap: 28, alignItems: 'center' }}>
          <ScoreRing value={score.total} grade={score.grade} />
          <div style={{ flex: 1, minWidth: 260 }}>
            <div className="eyebrow">Mission report · {scn.title}</div>
            <h2 style={{ fontSize: 30, margin: '4px 0' }}>{design.name}</h2>
            <div style={{ fontSize: 18, color: outcomeColor, fontWeight: 600 }}>{run.outcome === 'full' ? 'Full mission success' : run.outcome === 'partial' ? 'Partial mission success' : 'Mission did not reach minimum success'} · {score.label}</div>
            <div className="muted" style={{ marginTop: 4 }}>This flight: {run.endReason.toLowerCase()}, {(run.scienceFrac * 100).toFixed(0)}% science. Across {mc.runs} simulated flights: <b style={{ color: 'var(--text)' }}>{(mc.pFull * 100).toFixed(0)}% full</b>, {(mc.pPartial * 100).toFixed(0)}% partial, {(mc.pFail * 100).toFixed(0)}% failure.</div>
            {best[design.scenarioId] !== undefined && <div className="muted" style={{ fontSize: 13 }}>Your best score on this scenario: {best[design.scenarioId].toFixed(0)}</div>}
            <div className="row" style={{ marginTop: 14 }}>
              <button className="btn primary" onClick={back}>Improve this design</button>
              <button className="btn" onClick={refly}>Re-fly (new random events)</button>
              <button className="btn" onClick={() => { navigator.clipboard?.writeText(shareUrl(design)); setCopied(true); setTimeout(() => setCopied(false), 1500); }}>{copied ? 'Link copied!' : 'Copy share link'}</button>
              <button className="btn" onClick={() => download(`catalyx-report-${design.scenarioId}.md`, markdown(result), 'text/markdown')}>Download report</button>
              {gmatSupported(design) && <button className="btn" title="Starter script for NASA's General Mission Analysis Tool" onClick={() => download(`catalyx-${design.scenarioId}.script`, buildGmatScript(design, ev))}>Export to NASA GMAT</button>}
            </div>
          </div>
        </div>
      </div>

      <div className="grid" style={{ gridTemplateColumns: 'repeat(auto-fit,minmax(380px,1fr))', marginTop: 16 }}>
        <Panel title="Score breakdown" sub="What earned (and lost) points">
          <HBar label="Science return" value={score.science} max={45} />
          <HBar label="Engineering margins" value={score.margins} max={20} color="#b79cff" />
          <HBar label="Cost efficiency" value={score.cost} max={15} color="#ffb454" />
          <HBar label="Risk & reliability" value={score.risk} max={10} color="#7be495" />
          <HBar label="Process & learning" value={score.process} max={team?.started ? 4 : 10} color="#ff8a9a" />
          {team?.started && <HBar label="Teamwork" value={score.teamwork} max={6} color="#ffd27a" />}
          <div className="muted" style={{ fontSize: 13, marginTop: 8 }}>Scores use the average over {mc.runs} simulated flights, so luck on one flight cannot make or break your result.</div>
        </Panel>
        <Panel title="Distribution of outcomes" sub={`${mc.runs} Monte Carlo flights`}>
          <Histogram bins={mc.histogram} labels={['0% science', '100% science']} />
          <div className="muted" style={{ fontSize: 13.5, marginTop: 8 }}>Typical range (10th to 90th percentile): <b style={{ color: 'var(--text)' }}>{(mc.p10 * 100).toFixed(0)}% to {(mc.p90 * 100).toFixed(0)}%</b> of potential science. The mission reserve was exhausted in {(mc.budgetOverrunProb * 100).toFixed(0)}% of flights.</div>
          {mc.topCauses.length > 0 && (
            <div style={{ marginTop: 10 }}>
              <b style={{ fontSize: 13 }}>When flights fall short, the usual reason is:</b>
              {mc.topCauses.map((c) => <HBar key={c.cause} label={c.cause} value={c.share * 100} max={100} color="#ff8a9a" right={`${(c.share * 100).toFixed(0)}%`} />)}
            </div>
          )}
        </Panel>
      </div>

      <Panel title="Why it worked, and why it didn't" sub="Every number traces back to a decision you made" className="section">
        <div className="col">{insights.map((i, k) => <div key={k} className={`insight ${i.severity}`}><b>{i.title}</b><p>{i.detail}</p>{i.fix && <p className="fix">Try: {i.fix}</p>}</div>)}</div>
      </Panel>

      <div className="grid" style={{ gridTemplateColumns: 'repeat(auto-fit,minmax(380px,1fr))', marginTop: 16 }}>
        <Panel title="Science objectives">
          <table className="t"><thead><tr><th>Objective</th><th className="num">Expected</th><th className="num">This flight</th></tr></thead>
            <tbody>{ev.objectives.map((o) => (
              <tr key={o.id}><td><b>{o.title}</b><div className="muted" style={{ fontSize: 12.5 }}>{o.limiting === 'Not selected' ? 'Not selected' : o.limiting}</div></td><td className="num">{(o.achievement * 100).toFixed(0)}%</td><td className="num">{((run.objectiveAchievement[o.id] ?? 0) * 100).toFixed(0)}%</td></tr>
            ))}</tbody></table>
        </Panel>
        <Panel title="Requirements verification">
          <table className="t"><thead><tr><th>Requirement</th><th className="num">Result</th><th /></tr></thead>
            <tbody>{verification.map((v) => <tr key={v.req}><td>{v.req}</td><td className="num">{v.val}</td><td>{v.ok ? <Pill tone="green">Pass</Pill> : <Pill tone="red">Fail</Pill>}</td></tr>)}</tbody></table>
        </Panel>
        <Panel title="Engineering margins">
          <table className="t"><tbody>{margins.map((m) => <tr key={m.label}><td>{m.label}</td><td className="num">{m.value}</td><td style={{ width: 110 }}><div className={`bar ${m.q > 0.85 ? 'st-ok' : m.q > 0.5 ? 'st-warn' : 'st-bad'}`}><i style={{ width: `${m.q * 100}%` }} /></div></td></tr>)}</tbody></table>
        </Panel>
        <Panel title="Where the money went">
          <div className="row" style={{ gap: 18 }}>
            <Donut parts={costParts} centre={<div><b style={{ fontSize: 17 }}>${fmt(ev.cost.totalM)}M</b><div className="muted">of ${fmt(ev.cost.budgetM)}M</div></div>} />
            <div className="col" style={{ gap: 4, fontSize: 13.5 }}>{costParts.map((c) => <span key={c.label}><i style={{ display: 'inline-block', width: 10, height: 10, borderRadius: 3, background: c.color, marginRight: 6 }} />{c.label}: ${fmt(c.value)}M</span>)}</div>
          </div>
        </Panel>
      </div>

      {team?.started && (
        <Panel title="Team priorities" sub="Each role had a private goal. Teamwork scores how many the crew satisfied together." className="section">
          <div className="grid" style={{ gridTemplateColumns: 'repeat(auto-fit,minmax(240px,1fr))' }}>
            {ROLE_ORDER.map((r) => (
              <div key={r} className="rolecard" style={{ borderColor: priorities[r].met ? 'var(--green)' : 'var(--border)' }}>
                <h4 style={{ color: ROLES[r].color }}>{ROLES[r].name}</h4>
                <span className="muted" style={{ fontSize: 13.5 }}>{priorities[r].text}</span>
                <Pill tone={priorities[r].met ? 'green' : 'red'}>{priorities[r].met ? 'Achieved' : 'Missed'}</Pill>
              </div>
            ))}
          </div>
        </Panel>
      )}

      <Panel title={`Compared with ${scn.reference.name}`} className="section">
        <table className="t"><thead><tr><th /><th className="num">Your mission</th><th className="num">{scn.reference.name}</th></tr></thead>
          <tbody>
            <tr><td>Launch mass</td><td className="num">{fmt(ev.mass.wetKg)} kg</td><td className="num">{fmt(scn.reference.launchMassKg)} kg</td></tr>
            <tr><td>Orbit</td><td className="num">{ev.orbit.body === 'l2' ? 'L2 halo' : `${fmt(ev.orbit.altKm)} km, ${ev.orbit.incDeg.toFixed(0)}°`}</td><td className="num">{scn.reference.orbit}</td></tr>
            <tr><td>Cost (approximate)</td><td className="num">${fmt(ev.cost.totalM)}M</td><td className="num">${fmt(scn.reference.costM)}M</td></tr>
          </tbody></table>
        <div className="muted" style={{ fontSize: 13.5, marginTop: 8 }}>{scn.reference.blurb} <a href={scn.reference.url} target="_blank" rel="noreferrer">Read about the real mission on NASA's site</a></div>
      </Panel>
    </div>
  );
}
